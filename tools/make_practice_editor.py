"""Write the practice editor's settings (static/admin/test/config.yml) from the real ones (static/admin/config.yml).
The two differ only in where posts are kept: the practice copy keeps them in the browser. Run by build.sh, so the
field list is written once and the practice copy cannot fall behind."""
import os, re
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(here, "static", "admin", "config.yml")).read()
body = src[src.index("backend:"):]
body = re.sub(r"backend:\n(  .*\n)+", "backend:\n  name: test-repo\n", body, count=1)
head = ("# Practice copy of the editor, written by tools/make_practice_editor.py from ../config.yml. Do not edit this file.\n"
        "# Same fields, but posts are kept in the browser only (Sveltia's \"test-repo\" backend), so anyone can try writing\n"
        "# a post without touching the site's files. Open http://localhost:4176/admin/test/\n")
open(os.path.join(here, "static", "admin", "test", "config.yml"), "w").write(head + body)
